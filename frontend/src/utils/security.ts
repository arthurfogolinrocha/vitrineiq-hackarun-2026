function rotr(value: number, bits: number): number {
  return (value >>> bits) | (value << (32 - bits));
}

export function sha256Hex(input: string): string {
  const bytes = new TextEncoder().encode(input);
  const bitLen = bytes.length * 8;
  const paddedLen = Math.ceil((bytes.length + 9) / 64) * 64;
  const padded = new Uint8Array(paddedLen);
  padded.set(bytes);
  padded[bytes.length] = 0x80;

  const view = new DataView(padded.buffer);
  view.setUint32(paddedLen - 8, Math.floor(bitLen / 0x100000000), false);
  view.setUint32(paddedLen - 4, bitLen >>> 0, false);

  const h = new Uint32Array([
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a,
    0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
  ]);
  const w = new Uint32Array(64);

  for (let offset = 0; offset < paddedLen; offset += 64) {
    for (let i = 0; i < 16; i++) {
      w[i] = view.getUint32(offset + i * 4, false);
    }
    for (let i = 16; i < 64; i++) {
      const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3);
      const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) >>> 0;
    }

    let [a, b, c, d, e, f, g, hh] = h;
    for (let i = 0; i < 64; i++) {
      const S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const temp1 = (hh + S1 + ch + SHA256_K[i] + w[i]) >>> 0;
      const S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const temp2 = (S0 + maj) >>> 0;

      hh = g;
      g = f;
      f = e;
      e = (d + temp1) >>> 0;
      d = c;
      c = b;
      b = a;
      a = (temp1 + temp2) >>> 0;
    }

    h[0] = (h[0] + a) >>> 0;
    h[1] = (h[1] + b) >>> 0;
    h[2] = (h[2] + c) >>> 0;
    h[3] = (h[3] + d) >>> 0;
    h[4] = (h[4] + e) >>> 0;
    h[5] = (h[5] + f) >>> 0;
    h[6] = (h[6] + g) >>> 0;
    h[7] = (h[7] + hh) >>> 0;
  }

  return Array.from(h)
    .map((word) => word.toString(16).padStart(8, '0'))
    .join('');
}

export function sanitizeInput(input: string): string {
  if (!input || typeof input !== 'string') return '';

  // Remove tags de script e caracteres perigosos
  return input
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, '')
    .replace(/[<>]/g, (tag) => (tag === '<' ? '&lt;' : '&gt;'))
    .trim();
}

export function validateRequiredFields<T extends Record<string, unknown>>(
  data: T,
  requiredKeys: (keyof T)[]
): { isValid: boolean; missingFields: string[] } {
  const missingFields: string[] = [];

  for (const key of requiredKeys) {
    const value = data[key];
    if (value === undefined || value === null || (typeof value === 'string' && value.trim() === '')) {
      missingFields.push(String(key));
    }
  }

  return {
    isValid: missingFields.length === 0,
    missingFields,
  };
}

export function generateAuditHash(
  payload: string,
  prevHash: string = 'GENESIS_BLOCK_0000',
  id?: string,
  timestamp?: string
): string {
  const combined = `${prevHash}:${id || ''}:${timestamp || ''}:${payload}`;
  const digest = sha256Hex(combined);
  return `SEC-SHA-${digest.slice(0, 16).toUpperCase()}`;
}

export function containsRestrictedPatterns(text: string): boolean {
  // Guardrail para bloquear tentativa de prompt injection ou vazamento de segredos
  const patterns = [
    /ignore all previous instructions/i,
    /ignore (as|todas as) instru[cç][oõ]es anteriores/i,
    /system prompt reveal/i,
    /revele? (o )?prompt/i,
    /drop table/i,
    /delete from/i,
    /<iframe/i,
  ];
  return patterns.some((pattern) => pattern.test(text));
}
